"""Run the isolated restore-only worker using an existing simulation runtime."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile
import time
import urllib.request


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,indent=2)+'\n')


def run():
    bundle=Path(__file__).resolve().parent
    plan=json.loads((bundle/'plan.json').read_text())
    root=bundle.parent
    code=Path(plan['code'])
    runtime=Path(plan['runtime'])
    for name,digest in plan['bundle_sha256'].items():
        if sha256(bundle/name)!=digest:raise ValueError('Bundled code differs: '+name)
    for name,digest in plan['source_sha256'].items():
        if sha256(code/name)!=digest:raise ValueError('Frozen simulation source differs: '+name)
    # Copied from the verified existing worker, with its own content hash in plan.
    import runtime_environment
    runtime_environment.sha256=sha256
    runtime_environment.write_json=write_json
    scratch=root/'scratch';scratch.mkdir()
    env,gpu=runtime_environment._environment(
        {'runtime':str(runtime),'checkpoint':plan['unused_checkpoint_path'],
         'instance_id':plan['instance'],'run_id':plan['job_name'],
         'execution_name':plan['job_name']},
        {'supplemental_library':plan['supplemental_library']},root,scratch,scratch)
    env['PYTHONPATH']=':'.join(str(p) for p in [code/'scripts',code/'BEHAVIOR-1K/OmniGibson',code/'BEHAVIOR-1K/bddl3'])
    env['PYTHONDONTWRITEBYTECODE']='1'
    # All files generated by Isaac Sim remain in this job's isolated directory.
    for key,part in [('OMNIGIBSON_APPDATA_PATH','appdata'),('XDG_CACHE_HOME','cache'),
                     ('XDG_CONFIG_HOME','config'),('WARP_CACHE_PATH','warp')]:
        value=scratch/part;value.mkdir();env[key]=str(value)
    write_json(root/'runtime_receipt.json',{'gpu':gpu,'source_hashes_verified':len(plan['source_sha256']),
        'worker_sha256':sha256(bundle/'worker.py'),'model_calls':0})
    result=root/'results'
    with (root/'worker.log').open('x') as log:
        process=subprocess.run([str(runtime/'envs/b1k-eval/bin/python'),str(bundle/'worker.py'),
                                '--plan',str(bundle/'plan.json'),'--output',str(result)],
                               env=env,cwd=str(code),stdout=log,stderr=subprocess.STDOUT,
                               timeout=plan['worker_timeout_seconds'])
    if process.returncode:raise RuntimeError('Worker failed with exit '+str(process.returncode))
    report=json.loads((result/'result.json').read_text())
    if report['model_calls']!=0 or report['training'] is not False:
        raise ValueError('Worker exceeded restore-only scope')
    return {'state':'complete','restore_checks_passed':report['all_checks_passed'],
            'held_object_present':report['held_object_present']}


if __name__=='__main__':
    root=Path(__file__).resolve().parent.parent
    status={'state':'starting','started_at':time.time()}
    code=1
    try:
        status.update(run());code=0
    except BaseException as error:
        status.update(state='failed',error_type=type(error).__name__,error=str(error)[:1500])
    status['finished_at']=time.time()
    write_json(root/'driver_status.json',status)
    archive=root/'result.tar.gz'
    with tarfile.open(archive,'w:gz') as tar:
        for name in ['driver_status.json','runtime_receipt.json','worker.log','results']:
            p=root/name
            if p.exists():tar.add(p,arcname=name)
    # This URL is supplied in the process environment, never saved in an artifact.
    target=os.environ.get('RESTORE_PROBE_PUT_URL')
    if target:
        opener=urllib.request.build_opener(urllib.request.ProxyHandler({}))
        with opener.open(urllib.request.Request(target,data=archive.read_bytes(),method='PUT'),timeout=60) as response:
            if response.status not in (200,201,204):raise RuntimeError('Result upload failed')
    print(json.dumps(status),flush=True)
    sys.exit(code)
